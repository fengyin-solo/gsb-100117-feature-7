def build_console_seed() -> dict[str, list[dict[str, Any]]]:
    tasks: list[dict[str, Any]] = []
    checks: list[dict[str, Any]] = []
    dispatches: list[dict[str, Any]] = []
    check_seq = 1
    dispatch_seq = 1
    for task_def in _TASK_DEFS:
        task = {key: value for key, value in task_def.items() if key not in {"results"}}
        tasks.append(task)
        category = str(task["检查类别"])
        closed_results = task_def["results"]
        for seq, item_name in enumerate(_CHECK_ITEMS[category], start=1):
            result = closed_results[seq - 1] if closed_results else "待检"
            if task["status"] == "已取消":
                check_status = "已取消"
            elif closed_results:
                check_status = "已收口"
            else:
                check_status = "待检"
            checks.append({
                "id": check_seq,
                "检查编号": f"CHK-{task['id']:04d}-{seq}",
                "task_id": task["id"],
                "batch_id": task["batch_id"],
                "隧道id": task["隧道id"],
                "隧道编号": task["隧道编号"],
                "隧道名称": task["隧道名称"],
                "洞群": task["洞群"],
                "检查类别": category,
                "检查班组": _CREW[category],
                "班组快照": _CREW[category],
                "检查项目": item_name,
                "检查结果": result,
                "情况说明": "洞口段灯具点亮率不足" if result == "隐患整改" else "",
                "作业开始": task["作业开始"],
                "作业结束": task["作业结束"],
                "status": check_status,
                "收口时间": task["收口时间"] if closed_results else "",
                "收口结论": task["收口结论"] if closed_results else "",
                "收口负责人": task["收口负责人"] if closed_results else "",
                "pending": check_status == "待检",
                "abnormal": result == "隐患整改",
            })
            check_seq += 1

        # 已签发后的任务都有调度待办；作业中两类车（含封闭车）都派出
